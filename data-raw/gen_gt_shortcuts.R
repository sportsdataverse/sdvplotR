# Writes R/gt_theme_shortcuts.R: one thin gt_theme_<id>() per CURATED registry id,
# each a call to gt_theme_source(). The list is the same CURATED 20 as sdvplot's
# gt_theme_* shortcuts. Never hand-edit the output; edit this file and re-run:
#   Rscript data-raw/gen_gt_shortcuts.R           # write
#   Rscript data-raw/gen_gt_shortcuts.R --check   # exit 1 if the file has drifted

CURATED <- c(
  "basketball-reference", "datagolf", "fivethirtyeight-site", "wikipedia",
  "cleaning-the-glass", "bbc-sport", "opta-analyst", "our-world-in-data",
  "bloomberg-markets", "aer", "nzz", "guardian", "barttorvik", "espn-site",
  "gov-uk", "washington-post", "reuters-graphics", "formula1",
  "dunks-and-threes", "economist"
)

script_dir <- function() {
  f <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
  if (length(f)) dirname(normalizePath(f[[1]])) else normalizePath("data-raw")
}

root <- dirname(script_dir())
registry <- jsonlite::read_json(
  file.path(root, "inst", "extdata", "table_themes.json"),
  simplifyVector = FALSE
)$themes

one <- function(id) {
  t <- registry[[id]]
  if (is.null(t)) stop("CURATED id not in the registry: ", id, call. = FALSE)
  fn <- paste0("gt_theme_", gsub("-", "_", id))
  dark <- if (identical(t$darkPolicy, "none")) {
    "This theme is light-only: `mode = \"dark\"` is an error."
  } else {
    "`mode = \"dark\"` uses the theme's dark palette."
  }
  c(
    sprintf("#' %s table style for `gt` tables", t$source),
    "#'",
    sprintf("#' A shortcut for `gt_theme_source(gt_object, \"%s\")`: the %s table style", id, t$source),
    sprintf("#' from the surveyed registry (category `%s`). %s", t$category, dark),
    "#'",
    "#' @param gt_object A `gt` table object to modify.",
    "#' @param mode `\"light\"` (default) or `\"dark\"`.",
    "#' @param density Character. The type and padding scale. One of `\"comfortable\"`,",
    "#'   `\"compact\"` or `\"social\"`.",
    "#'",
    "#' @returns A modified `gt` table with the theme applied.",
    "#'",
    "#' @examples",
    "#' library(gt)",
    "#' central <- subset(",
    "#'   sdv_example_standings, division == \"Central\",",
    "#'   c(team_name, wins, losses, win_pct)",
    "#' )",
    sprintf("#' gt(central) |> %s()", fn),
    "#'",
    "#' @seealso [gt_theme_source()], [sdv_table_themes()]",
    "#' @export",
    sprintf("%s <- function(gt_object, mode = \"light\", density = \"comfortable\") {", fn),
    sprintf("  gt_theme_source(gt_object, \"%s\", mode = mode, density = density)", id),
    "}",
    ""
  )
}

out <- c(
  "# Generated by data-raw/gen_gt_shortcuts.R. Do not edit by hand.",
  "",
  unlist(lapply(CURATED, one))
)
out <- out[-length(out)] # no trailing blank line

path <- file.path(root, "R", "gt_theme_shortcuts.R")
want <- paste0(paste(out, collapse = "\n"), "\n")

if ("--check" %in% commandArgs(TRUE)) {
  have <- if (file.exists(path)) paste(readLines(path, warn = FALSE, encoding = "UTF-8"), collapse = "\n") else ""
  if (!identical(paste0(have, "\n"), want)) {
    message("R/gt_theme_shortcuts.R is out of date: run `Rscript data-raw/gen_gt_shortcuts.R`")
    quit(status = 1L)
  }
  quit(status = 0L)
}
writeBin(charToRaw(want), path) # binary: LF endings on every platform
message("wrote ", path)
